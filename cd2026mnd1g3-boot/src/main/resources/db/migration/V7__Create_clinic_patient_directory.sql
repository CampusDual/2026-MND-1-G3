CREATE TABLE IF NOT EXISTS clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    telefono VARCHAR(30),
    email VARCHAR(160),
    activa BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS propietarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    apellidos VARCHAR(120) NOT NULL,
    dni_nif VARCHAR(20),
    telefono VARCHAR(30) NOT NULL,
    email VARCHAR(160),
    nombre_normalizado VARCHAR(250) NOT NULL,
    notificaciones_internas BOOLEAN DEFAULT TRUE NOT NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT fk_propietario_clinica FOREIGN KEY (clinica_id) REFERENCES clinicas (id)
);

CREATE TABLE IF NOT EXISTS pacientes_mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    propietario_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    nombre_normalizado VARCHAR(100) NOT NULL,
    especie VARCHAR(20) NOT NULL,
    raza VARCHAR(100),
    raza_normalizada VARCHAR(100),
    microchip VARCHAR(30),
    fecha_nacimiento DATE,
    fecha_nacimiento_estimada BOOLEAN DEFAULT FALSE NOT NULL,
    edad_aprox_anos INTEGER,
    edad_aprox_meses INTEGER,
    sexo VARCHAR(20) DEFAULT 'DESCONOCIDO' NOT NULL,
    esterilizado VARCHAR(20) DEFAULT 'DESCONOCIDO' NOT NULL,
    peso_inicial DOUBLE,
    unidad_peso VARCHAR(2),
    alergias BOOLEAN DEFAULT FALSE NOT NULL,
    manejo_nervioso BOOLEAN DEFAULT FALSE NOT NULL,
    patologia_cronica BOOLEAN DEFAULT FALSE NOT NULL,
    nota_banderas VARCHAR(500),
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    estado_paciente VARCHAR(20) DEFAULT 'ACTIVO' NOT NULL,
    notas VARCHAR(1000),
    CONSTRAINT fk_paciente_clinica FOREIGN KEY (clinica_id) REFERENCES clinicas (id),
    CONSTRAINT fk_paciente_propietario FOREIGN KEY (propietario_id) REFERENCES propietarios (id),
    CONSTRAINT uq_paciente_microchip_clinica UNIQUE (clinica_id, microchip)
);

CREATE TABLE IF NOT EXISTS consultas_clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    propietario_id BIGINT NOT NULL,
    fecha_consulta TIMESTAMP NOT NULL,
    motivo VARCHAR(500),
    notas VARCHAR(2000),
    proxima_vacuna DATE,
    CONSTRAINT fk_consulta_clinica FOREIGN KEY (clinica_id) REFERENCES clinicas (id),
    CONSTRAINT fk_consulta_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes_mascotas (id),
    CONSTRAINT fk_consulta_propietario FOREIGN KEY (propietario_id) REFERENCES propietarios (id)
);

CREATE TABLE IF NOT EXISTS recetas_clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    consulta_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    medicamento_id BIGINT,
    lote_stock_id BIGINT,
    indicaciones VARCHAR(1000),
    fecha_emision DATE NOT NULL,
    CONSTRAINT fk_receta_clinica FOREIGN KEY (clinica_id) REFERENCES clinicas (id),
    CONSTRAINT fk_receta_consulta FOREIGN KEY (consulta_id) REFERENCES consultas_clinicas (id),
    CONSTRAINT fk_receta_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes_mascotas (id)
);

CREATE INDEX IF NOT EXISTS idx_propietarios_clinica_nombre
    ON propietarios (clinica_id, nombre_normalizado);
CREATE INDEX IF NOT EXISTS idx_propietarios_clinica_telefono
    ON propietarios (clinica_id, telefono);
CREATE INDEX IF NOT EXISTS idx_propietarios_clinica_dni
    ON propietarios (clinica_id, dni_nif);
CREATE INDEX IF NOT EXISTS idx_pacientes_clinica_especie_raza
    ON pacientes_mascotas (clinica_id, especie, raza);
CREATE INDEX IF NOT EXISTS idx_pacientes_microchip
    ON pacientes_mascotas (microchip);

MERGE INTO clinicas AS c
USING (VALUES (1, 'Clínica Principal', '+34910000000', 'clinica@example.test', TRUE))
    AS seed(id, nombre, telefono, email, activa)
ON c.id = seed.id
WHEN NOT MATCHED THEN
    INSERT (id, nombre, telefono, email, activa)
    VALUES (seed.id, seed.nombre, seed.telefono, seed.email, seed.activa);
