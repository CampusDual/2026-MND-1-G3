CREATE TABLE IF NOT EXISTS clinics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    tax_id VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password VARCHAR(120) NOT NULL,
    enabled BOOLEAN NOT NULL,
    name VARCHAR(120),
    phone VARCHAR(30),
    email VARCHAR(160),
    app_role VARCHAR(30),
    clinica_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS farms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    rega_code VARCHAR(30) NOT NULL UNIQUE,
    main_species VARCHAR(30) NOT NULL,
    manager_name VARCHAR(120) NOT NULL,
    veterinarian_assigned_phone VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS animals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ear_tag VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100),
    species VARCHAR(30) NOT NULL,
    birth_date DATE NOT NULL,
    health_status VARCHAR(30) NOT NULL,
    estado_sanitario VARCHAR(40) NOT NULL,
    fecha_fin_retirada DATE,
    notas VARCHAR(1000),
    breed VARCHAR(100),
    clinica_id BIGINT NOT NULL,
    owner_id BIGINT,
    microchip VARCHAR(30),
    normalized_name VARCHAR(100),
    notifications_enabled BOOLEAN NOT NULL,
    farm_id BIGINT NOT NULL,
    FOREIGN KEY (farm_id) REFERENCES farms(id)
);

CREATE TABLE IF NOT EXISTS protocol_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    title VARCHAR(150) NOT NULL,
    application_date DATE NOT NULL,
    withdrawal_days INTEGER NOT NULL,
    withdrawal_end_date DATE,
    next_reminder_days INTEGER,
    next_cycle_days INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    animal_id BIGINT,
    farm_id BIGINT NOT NULL,
    FOREIGN KEY (animal_id) REFERENCES animals(id),
    FOREIGN KEY (farm_id) REFERENCES farms(id)
);

CREATE TABLE IF NOT EXISTS medicamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    nombre_comercial VARCHAR(150) NOT NULL,
    principio_activo VARCHAR(150) NOT NULL,
    especie_destino VARCHAR(30) NOT NULL,
    categoria_pran VARCHAR(5) NOT NULL,
    dias_retirada_defecto INTEGER NOT NULL,
    stock_minimo_alerta DOUBLE NOT NULL
);

CREATE TABLE IF NOT EXISTS lotes_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_id BIGINT NOT NULL,
    numero_lote VARCHAR(80) NOT NULL,
    fecha_caducidad DATE NOT NULL,
    proveedor VARCHAR(150),
    FOREIGN KEY (medicamento_id) REFERENCES medicamentos(id)
);

CREATE TABLE IF NOT EXISTS movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    lote_stock_id BIGINT NOT NULL,
    tipo_movimiento VARCHAR(30) NOT NULL,
    cantidad DOUBLE NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    veterinario_id BIGINT,
    animal_id BIGINT,
    explotacion_id BIGINT,
    protocolo_evento_id BIGINT,
    FOREIGN KEY (lote_stock_id) REFERENCES lotes_stock(id)
);

CREATE TABLE IF NOT EXISTS alertas_sistema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    destinatario_rol VARCHAR(30) NOT NULL,
    tipo_alerta VARCHAR(40) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    fecha_programada TIMESTAMP NOT NULL,
    leida BOOLEAN DEFAULT FALSE NOT NULL,
    confirmada_por_granja BOOLEAN DEFAULT FALSE NOT NULL,
    explotacion_id BIGINT,
    animal_id BIGINT
);

CREATE INDEX IF NOT EXISTS idx_farms_clinica ON farms(clinica_id);
CREATE INDEX IF NOT EXISTS idx_animals_farm ON animals(farm_id);
CREATE INDEX IF NOT EXISTS idx_animals_clinica ON animals(species, breed);
CREATE INDEX IF NOT EXISTS idx_protocol_clinica ON protocol_events(clinica_id);
CREATE INDEX IF NOT EXISTS idx_movements_clinica ON movimientos_inventario(clinica_id, fecha_hora);
