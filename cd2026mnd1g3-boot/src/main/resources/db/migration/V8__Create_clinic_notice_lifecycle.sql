CREATE TABLE IF NOT EXISTS avisos_clinicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    propietario_id BIGINT NOT NULL,
    categoria VARCHAR(20) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    detalle_clinico VARCHAR(2000),
    fecha_objetivo DATE NOT NULL,
    estado VARCHAR(20) DEFAULT 'PENDIENTE' NOT NULL,
    intentos INTEGER DEFAULT 0 NOT NULL,
    ultimo_intento TIMESTAMP,
    ultimo_usuario VARCHAR(80),
    fecha_inicio DATE,
    fecha_fin DATE,
    progreso VARCHAR(30),
    motivo_descarte VARCHAR(30),
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cancelado_por_baja BOOLEAN DEFAULT FALSE NOT NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT fk_aviso_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes_mascotas (id),
    CONSTRAINT fk_aviso_propietario FOREIGN KEY (propietario_id) REFERENCES propietarios (id)
);

CREATE INDEX IF NOT EXISTS idx_avisos_clinica_estado_fecha
    ON avisos_clinicos (clinica_id, estado, fecha_objetivo);
CREATE INDEX IF NOT EXISTS idx_avisos_paciente_activo
    ON avisos_clinicos (paciente_id, activo);
