CREATE TABLE IF NOT EXISTS propietarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    apellidos VARCHAR(120) NOT NULL,
    telefono_e164 VARCHAR(20),
    email VARCHAR(160),
    dni VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS paciente_mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    propietario_id BIGINT NOT NULL,
    nombre VARCHAR(100),
    especie VARCHAR(30) NOT NULL,
    raza VARCHAR(100),
    microchip VARCHAR(30),
    fecha_nacimiento DATE,
    estado_vacunal VARCHAR(30) NOT NULL,
    proxima_vacuna DATE,
    FOREIGN KEY (propietario_id) REFERENCES propietarios(id)
);

CREATE TABLE IF NOT EXISTS consultas_clinica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL,
    mascota_id BIGINT NOT NULL,
    fecha TIMESTAMP NOT NULL,
    motivo VARCHAR(500),
    diagnostico VARCHAR(1000),
    FOREIGN KEY (mascota_id) REFERENCES paciente_mascotas(id)
);

CREATE TABLE IF NOT EXISTS recetas_clinica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL,
    medicamento VARCHAR(150) NOT NULL,
    dosis VARCHAR(120),
    indicaciones VARCHAR(500),
    FOREIGN KEY (consulta_id) REFERENCES consultas_clinica(id)
);

CREATE INDEX IF NOT EXISTS idx_pacientes_clinica_species_breed
    ON paciente_mascotas(clinica_id, especie, raza);
CREATE INDEX IF NOT EXISTS idx_pacientes_clinica_microchip
    ON paciente_mascotas(clinica_id, microchip);
CREATE INDEX IF NOT EXISTS idx_propietarios_clinica_nombre
    ON propietarios(clinica_id, nombre, apellidos);
