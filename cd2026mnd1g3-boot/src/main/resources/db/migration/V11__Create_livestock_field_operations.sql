CREATE TABLE IF NOT EXISTS ganaderia_operaciones_campo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(64) NOT NULL,
    clinica_id BIGINT NOT NULL,
    farm_id BIGINT NOT NULL,
    animal_id BIGINT,
    tipo_operacion VARCHAR(40) NOT NULL,
    detalle VARCHAR(2000),
    estado VARCHAR(20) DEFAULT 'PENDIENTE' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_sincronizacion TIMESTAMP,
    CONSTRAINT uq_operacion_campo_clinica UNIQUE (clinica_id, operation_id),
    CONSTRAINT fk_operacion_campo_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE INDEX IF NOT EXISTS idx_operaciones_campo_clinica_estado
    ON ganaderia_operaciones_campo (clinica_id, estado, fecha_creacion);
